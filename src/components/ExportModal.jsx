import React, { useState } from 'react';
import { X, Download, Copy, Printer, Check, FileText } from 'lucide-react';

export default function ExportModal({ project, isOpen, onClose }) {
  const [copied, setCopied] = useState(false);

  if (!isOpen || !project) return null;

  // Generate markdown string
  const generateMarkdown = () => {
    let md = `# ${project.objectName} — Workshop Build Guide\n\n`;
    md += `> Source Video: [${project.title}](${project.url}) by ${project.author || 'Creator'}\n\n`;
    md += `## 📋 Project Summary\n`;
    md += `- **Category:** ${project.category || 'Woodworking'}\n`;
    md += `- **Difficulty:** ${project.difficulty || 'Intermediate'}\n`;
    md += `- **Estimated Time:** ${project.estimatedTime || 'N/A'}\n`;
    md += `- **Estimated Cost:** ${project.estimatedCost || 'N/A'}\n`;
    if (project.dimensions) md += `- **Dimensions:** ${project.dimensions}\n`;
    md += `\n${project.overview}\n\n`;

    md += `## 🪵 Bill of Materials & Cut List\n`;
    (project.materials || []).forEach(m => {
      md += `- [ ] **${m.item}** — ${m.quantity}${m.dimensions ? ` (${m.dimensions})` : ''}${m.notes ? ` *[${m.notes}]*` : ''}\n`;
    });
    md += `\n`;

    md += `## 🛠️ Required Tools\n`;
    (project.tools || []).forEach(t => {
      md += `- [ ] ${t.name} *(${t.category})*\n`;
    });
    md += `\n`;

    if (project.safetyWarnings && project.safetyWarnings.length > 0) {
      md += `## ⚠️ Safety Precautions\n`;
      project.safetyWarnings.forEach(w => {
        md += `- ${w}\n`;
      });
      md += `\n`;
    }

    md += `## 📝 Chronological Step-by-Step Instructions\n\n`;
    (project.steps || []).forEach(s => {
      md += `### Step ${s.stepNumber}: ${s.title} [${s.timestamp}]\n`;
      md += `**Phase:** ${s.phase}\n\n`;
      md += `${s.description}\n\n`;
      if (s.toolsUsed && s.toolsUsed.length > 0) {
        md += `*Tools Used:* ${s.toolsUsed.join(', ')}\n\n`;
      }
      if (s.proTip) {
        md += `> **Pro Tip:** ${s.proTip}\n\n`;
      }
      if (s.safetyNote) {
        md += `> **Safety:** ${s.safetyNote}\n\n`;
      }
    });

    md += `---\n*Generated by MakerSteps AI on ${new Date().toLocaleDateString()}*\n`;
    return md;
  };

  const handleDownloadMarkdown = () => {
    const md = generateMarkdown();
    const blob = new Blob([md], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${project.objectName.toLowerCase().replace(/[^a-z0-9]/g, '-')}-build-guide.md`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  const handleCopy = async () => {
    const md = generateMarkdown();
    await navigator.clipboard.writeText(md);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 bg-black/70 backdrop-blur-sm flex items-center justify-center p-4">
      <div className="bg-gray-900 border border-gray-800 rounded-2xl max-w-2xl w-full p-6 shadow-2xl overflow-hidden flex flex-col max-h-[90vh]">
        {/* Header */}
        <div className="flex items-center justify-between pb-4 border-b border-gray-800">
          <div className="flex items-center space-x-2">
            <FileText className="w-5 h-5 text-amber-400" />
            <h3 className="text-lg font-bold text-white">Export Workshop Guide</h3>
          </div>
          <button
            type="button"
            onClick={onClose}
            className="p-1 rounded-lg text-gray-400 hover:text-white hover:bg-gray-800 transition"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content Preview */}
        <div className="my-4 p-4 rounded-xl bg-gray-950 border border-gray-800 overflow-y-auto flex-1 font-mono text-xs text-gray-300 whitespace-pre-wrap">
          {generateMarkdown()}
        </div>

        {/* Action Buttons */}
        <div className="pt-3 border-t border-gray-800 flex flex-wrap items-center justify-between gap-2">
          <div className="flex items-center space-x-2">
            <button
              type="button"
              onClick={handleCopy}
              className="inline-flex items-center px-3.5 py-2 rounded-xl text-xs sm:text-sm font-medium bg-gray-800 hover:bg-gray-700 text-gray-200 border border-gray-700 transition"
            >
              {copied ? (
                <>
                  <Check className="w-4 h-4 mr-1.5 text-emerald-400" />
                  Copied to Clipboard!
                </>
              ) : (
                <>
                  <Copy className="w-4 h-4 mr-1.5" />
                  Copy Markdown
                </>
              )}
            </button>

            <button
              type="button"
              onClick={() => {
                onClose();
                setTimeout(() => window.print(), 300);
              }}
              className="inline-flex items-center px-3.5 py-2 rounded-xl text-xs sm:text-sm font-medium bg-gray-800 hover:bg-gray-700 text-gray-200 border border-gray-700 transition"
            >
              <Printer className="w-4 h-4 mr-1.5 text-gray-400" />
              Print / Save PDF
            </button>
          </div>

          <button
            type="button"
            onClick={handleDownloadMarkdown}
            className="inline-flex items-center px-4 py-2 rounded-xl text-xs sm:text-sm font-semibold bg-amber-600 hover:bg-amber-500 text-white shadow-lg shadow-amber-600/20 transition"
          >
            <Download className="w-4 h-4 mr-1.5" />
            Download .MD File
          </button>
        </div>
      </div>
    </div>
  );
}
